//! `nixos:NAME` — a package in the machine's **system configuration**, not in a profile (`J5`).
//!
//! **Why this is not the `nix:` backend with a flag.** `nix profile install` is right for the
//! Nix package manager wherever it runs — a Mac, an Ubuntu box, a NixOS box where somebody wants
//! a scratch tool for one account. On NixOS it is also a *side door*: the profile sits outside
//! the system generation, no `nixos-rebuild` accounts for it, and the machine ends up with two
//! sources of truth. `nixos:` is the other answer — the package goes in the configuration NixOS
//! itself reads, and an install becomes a system generation.
//!
//! Two prefixes rather than one word whose meaning changes per host (owner ruling, 2026-08-16).
//! A NixOS user may legitimately want both, and only two names can say so; and a config file
//! shared across machines keeps meaning the same thing everywhere, which one name could not.
//!
//! **Shall owns one file and never rewrites yours.** `shall-packages.nix` is regenerated from
//! the model; `configuration.nix` gets at most one `imports` line, appended once and guarded, and
//! is otherwise never touched. Parsing a hand-edited Nix expression to edit it in place is a
//! language problem with an ugly failure mode, and it buys nothing. The shape is `pacman`'s repo
//! support one directory over: write `/etc/pacman.d/shall-<name>.conf`, add one `Include =` line,
//! never rewrite the body.
//!
//! **What is proven and what is not.** The renderer below is pure and hermetically tested, and
//! its output is checked as *valid Nix* by `nix-instantiate --parse` — the risk that matters,
//! since a file nix cannot parse breaks the user's whole system configuration rather than just
//! Shall. `nixos-rebuild switch` against a real NixOS is argv-checked and **not executed**: no
//! container available is NixOS (`nixos/nix` is the package manager on a minimal base — no
//! `/etc/NIXOS`, no `nixos-rebuild`, no systemd), and that bound is recorded in `J5` rather than
//! left for a green suite to imply.

